    n_asientos = db.execute("SELECT COUNT(*) AS n FROM asientos").fetchone()["n"]
    return render_template(
        "index.html",
        activo=activo,
        pasivo=pasivo,
        patrimonio=patrimonio,
        ingresos=ingresos,
        gastos=gastos,
        utilidad=utilidad,
        n_cuentas=n_cuentas,
        n_asientos=n_asientos,
    )


