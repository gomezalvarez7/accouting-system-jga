def get_db():
    if "db" not in g:
        if not DATABASE_URL:
            raise RuntimeError("Falta configurar DATABASE_URL en el entorno.")
        g.db = psycopg.connect(DATABASE_URL, row_factory=dict_row)
    return g.db


@app.teardown_appcontext
def close_db(exception=None):
    db = g.pop("db", None)
    if db is not None:
        db.close()


def init_db():
    """Crea las tablas necesarias en PostgreSQL sin borrar datos existentes."""
    if not DATABASE_URL:
        return
    with psycopg.connect(DATABASE_URL, row_factory=dict_row) as db:
        db.execute("""
            CREATE TABLE IF NOT EXISTS cuentas (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                codigo TEXT NOT NULL UNIQUE, nombre TEXT NOT NULL,
                tipo TEXT NOT NULL CHECK(tipo IN ('Activo','Pasivo','Patrimonio','Ingreso','Gasto')),
                saldo_inicial DOUBLE PRECISION NOT NULL DEFAULT 0,
                activa INTEGER NOT NULL DEFAULT 1
            )
        """)
        db.execute("""
            CREATE TABLE IF NOT EXISTS asientos (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                numero BIGINT NOT NULL, fecha TEXT NOT NULL, descripcion TEXT NOT NULL
            )
        """)
        db.execute("""
            CREATE TABLE IF NOT EXISTS usuarios (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                usuario TEXT NOT NULL UNIQUE, clave_hash TEXT NOT NULL,
                es_admin INTEGER NOT NULL DEFAULT 0
            )
        """)
        db.execute("""
            CREATE TABLE IF NOT EXISTS movimientos (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                asiento_id BIGINT NOT NULL REFERENCES asientos(id) ON DELETE CASCADE,
                cuenta_id BIGINT NOT NULL REFERENCES cuentas(id),
                detalle TEXT, debe DOUBLE PRECISION NOT NULL DEFAULT 0,
                haber DOUBLE PRECISION NOT NULL DEFAULT 0
            )
        """)
        db.execute("ALTER TABLE usuarios ADD COLUMN IF NOT EXISTS es_admin INTEGER NOT NULL DEFAULT 0")
        total = db.execute("SELECT COUNT(*) AS n FROM usuarios").fetchone()["n"]
        if total == 0:
            db.execute(
                "INSERT INTO usuarios (usuario, clave_hash, es_admin) VALUES (%s, %s, 1)",
                (USUARIO_INICIAL, generate_password_hash(CLAVE_INICIAL)),
            )
        hay_admin = db.execute("SELECT 1 FROM usuarios WHERE es_admin = 1 LIMIT 1").fetchone()
        if not hay_admin:
            db.execute("UPDATE usuarios SET es_admin = 1 WHERE id = (SELECT MIN(id) FROM usuarios)")


